from __future__ import annotations

import inspect
from contextvars import ContextVar
from dataclasses import replace
from pathlib import Path

from ..channels.native import field
from .catalog import digest, skill_entries
from .patches import Patches

SKILL_SCOPE = ContextVar("enishi_skill_scope", default=None)


class SkillIntegration:
    def __init__(self, service):
        self.service = service
        self.patches = Patches()

    def install(self, agent_module=None, manager_class=None):
        if agent_module is None:
            from astrbot.core import astr_main_agent as agent_module
            from astrbot.core.skills.skill_manager import SkillManager

            manager_class = SkillManager
        self.patches.add(agent_module, "_ensure_persona_and_skills", self._scope)
        self.patches.add(agent_module, "build_skills_prompt", self._render)
        if manager_class is not None:
            for name in (
                "set_skill_active",
                "delete_skill",
                "install_skill_from_zip",
                "set_sandbox_skills_cache",
            ):
                self.patches.add(manager_class, name, self._changed)

    def _changed(self, original):
        observed = self.service.observer._mutation(original)
        if inspect.iscoroutinefunction(original):

            async def changed(*args, **kwargs):
                try:
                    return await observed(*args, **kwargs)
                finally:
                    self.service.skill_epoch += 1
        else:

            def changed(*args, **kwargs):
                try:
                    return observed(*args, **kwargs)
                finally:
                    self.service.skill_epoch += 1

        return changed

    def _scope(self, original):
        async def wrapped(req, cfg, plugin_context, event, *args, **kwargs):
            if plugin_context is not self.service.context or not self.service.enabled(
                event
            ):
                return await original(req, cfg, plugin_context, event, *args, **kwargs)
            token = SKILL_SCOPE.set((self, req, cfg))
            try:
                return await original(req, cfg, plugin_context, event, *args, **kwargs)
            finally:
                self.service.scope_skills[event.unified_msg_origin] = {
                    key: entry
                    for key, entry in getattr(req, "_enishi_skill_entries", {}).items()
                    if field(entry.value, "source_type") == "workspace"
                }
                SKILL_SCOPE.reset(token)

        return wrapped

    def _render(self, original):
        def wrapped(skills):
            native = original(skills)
            scope = SKILL_SCOPE.get()
            if (
                scope is None
                or scope[0] is not self
                or not self.service.policy.fold_skills
            ):
                return native
            # Only inspect the section generated by this exact native function.
            # Descriptions and the rest of system_prompt are never parsed/replaced.
            prefix, marker, rules = native.rpartition("### Skill rules")
            start = rules.find("2. **When to trigger**")
            if not marker or start < 0:
                self.service.failure(
                    "Skill renderer contract", ValueError("native Skill rules changed")
                )
                return native
            before_grounding, grounding, after_grounding = rules[start:].partition(
                "3. **Mandatory grounding**"
            )
            _, progressive, remaining_rules = after_grounding.partition(
                "4. **Progressive disclosure**"
            )
            if not grounding or not progressive:
                self.service.failure(
                    "Skill renderer contract",
                    ValueError("native grounding rules changed"),
                )
                return native
            folded_rules = (
                before_grounding
                + "3. **Mandatory grounding** — Before executing a skill, read its complete SKILL.md "
                "through enishi_load, which reads the registered path in the current runtime. "
                "The expanded resource includes the absolute path; resolve relative references from that directory. "
                "Never rely on memory or assumptions about the content.\n"
                + progressive
                + remaining_rules
            )
            runtime = scope[2].get("computer_use_runtime", "none")
            entries = skill_entries(skills, local_metadata=runtime in {"local", "none"})
            entries = {
                key: replace(
                    entry,
                    revision=digest(
                        [
                            entry.revision,
                            self.service.skill_epoch,
                            self.service.skill_boot,
                        ]
                    ),
                )
                for key, entry in entries.items()
            }
            setattr(scope[1], "_enishi_skill_entries", entries)
            self.service.discover(entries)
            visible = [
                entry
                for entry in entries.values()
                if self.service.store.mode(entry) == "primary"
            ]
            from .catalog import render

            rendered = (
                "## Skills\n\n"
                f"{len(entries)} eligible skills are available through enishi_find(kind='skill'). "
                "Use enishi_load with the returned ID to read the complete SKILL.md into this request. "
                "Search named or relevant skills before working; loading preserves full instructions.\n"
                + render(visible)
                + "\n\n### Skill rules\n\n"
                + "1. **Discovery** — The discovery tool lists the eligible inventory for this session.\n"
                + folded_rules
            )
            blocks = getattr(scope[1], "_enishi_skill_blocks", [])
            blocks.append((rendered, native))
            setattr(scope[1], "_enishi_skill_blocks", blocks)
            return rendered

        return wrapped

    def close(self):
        self.patches.close()


async def read_skill(context, event, skill):
    config = context.get_config(umo=event.unified_msg_origin) or {}
    runtime = config.get("provider_settings", {}).get("computer_use_runtime", "none")
    path = str(field(skill, "path", ""))
    if not path or path.replace("\\", "/").rsplit("/", 1)[-1] != "SKILL.md":
        raise ValueError("Skill 没有有效的原生 SKILL.md 定位")
    if runtime in {"none", "local"} and field(skill, "source_type") != "sandbox_only":
        import asyncio

        return await asyncio.to_thread(Path(path).read_text, encoding="utf-8-sig")
    if runtime == "none":
        raise ValueError("此 Skill 位于沙箱中，当前会话未启用沙箱运行环境")
    from astrbot.core.computer.computer_client import get_booter

    booter = await get_booter(context, event.unified_msg_origin)
    result = await booter.fs.read_file(path, encoding="utf-8", offset=None, limit=None)
    if result.get("success") is False or not isinstance(result.get("content"), str):
        raise ValueError("无法从当前运行环境完整读取 Skill")
    return result["content"]
